package io.github.abdurazaaqmohammed.util.hash;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertNotNull;
import static org.junit.Assert.assertNull;
import static org.junit.Assert.assertTrue;

import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.rules.TemporaryFolder;

import java.io.ByteArrayInputStream;
import java.io.File;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;

/**
 * Pure coverage for the checksum manifest layer: hash vectors, conventional
 * .sfv / .md5 generation, safe manifest name parsing (no absolute paths or
 * traversal) and verification round-trips on real temp files.
 */
public class HashUtilTest {

    @Rule
    public TemporaryFolder folder = new TemporaryFolder();

    private File dir;

    @Before
    public void setUp() throws Exception {
        dir = folder.newFolder("payload");
    }

    private static File write(File parent, String name, String content) throws Exception {
        File f = new File(parent, name);
        try (FileOutputStream out = new FileOutputStream(f)) {
            out.write(content.getBytes(StandardCharsets.UTF_8));
        }
        return f;
    }

    private static String hashOfFile(String content, String algorithm) throws Exception {
        try (InputStream in = new ByteArrayInputStream(content.getBytes(StandardCharsets.UTF_8))) {
            return HashUtil.hashStream(in, algorithm);
        }
    }

    private static List<HashUtil.CheckResult> verify(HashUtil.ManifestEntry[] entries,
                                                     String algorithm,
                                                     HashUtil.EntryOpener opener) {
        List<HashUtil.ManifestEntry> list = new ArrayList<>();
        for (HashUtil.ManifestEntry e : entries) list.add(e);
        return HashUtil.verifyEntries(algorithm, list, opener);
    }

    @Test
    public void crc32AndMd5KnownVectors() throws Exception {
        assertEquals("cbf43926", hashOfFile("123456789", "CRC32"));
        assertEquals("00000000", hashOfFile("", "CRC32"));
        assertEquals("900150983cd24fb0d6963f7d28e17f72", hashOfFile("abc", "MD5"));
        assertEquals("5d41402abc4b2a76b9719d911017c592", hashOfFile("hello", "MD5"));
    }

    @Test
    public void generateSfvProducesConventionalLines() throws Exception {
        File a = write(dir, "a.txt", "hello");
        File b = write(dir, "b c.txt", "world");

        String sfv = HashUtil.generateSfv(new ArrayList<>(List.of(a, b)));

        assertTrue("SFV header comment", sfv.startsWith("; Generated by MP-Manager\r\n"));
        String expectedA = "a.txt " + hashOfFile("hello", "CRC32").toUpperCase();
        String expectedB = "b c.txt " + hashOfFile("world", "CRC32").toUpperCase();
        assertTrue(sfv, sfv.contains(expectedA + "\r\n"));
        assertTrue(sfv, sfv.contains(expectedB + "\r\n"));
    }

    @Test
    public void generateMd5ProducesMd5sumLines() throws Exception {
        File a = write(dir, "a.txt", "hello");
        File b = write(dir, "b c.txt", "world");

        String md5 = HashUtil.generateMd5(new ArrayList<>(List.of(a, b)));

        assertTrue(md5, md5.contains(hashOfFile("hello", "MD5") + "  a.txt\n"));
        assertTrue(md5, md5.contains(hashOfFile("world", "MD5") + "  b c.txt\n"));
        assertFalse("lowercase hex", md5.contains(hashOfFile("hello", "MD5").toUpperCase()));
    }

    @Test
    public void verifyRoundTripMd5IncludingNamesWithSpaces() throws Exception {
        write(dir, "a.txt", "hello");
        write(dir, "b c.txt", "world");
        File manifest = write(dir, "files.md5",
                HashUtil.generateMd5(new ArrayList<>(List.of(new File(dir, "a.txt"), new File(dir, "b c.txt")))));

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(2, results.size());
        for (HashUtil.CheckResult r : results) {
            assertTrue(r.fileName + " valid", r.valid);
            assertFalse(r.missing);
            assertFalse(r.rejected);
        }
    }

    @Test
    public void verifyRoundTripSfvCaseInsensitive() throws Exception {
        write(dir, "a.txt", "hello");
        File manifest = write(dir, "payload.sfv",
                HashUtil.generateSfv(new ArrayList<>(List.of(new File(dir, "a.txt")))));

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(1, results.size());
        assertTrue(results.get(0).valid);
        assertEquals("a.txt", results.get(0).fileName);
    }

    @Test
    public void verifyDetectsChangedFile() throws Exception {
        write(dir, "a.txt", "hello");
        write(dir, "b.txt", "world");
        File manifest = write(dir, "payload.md5", HashUtil.generateMd5(
                new ArrayList<>(List.of(new File(dir, "a.txt"), new File(dir, "b.txt")))));
        write(dir, "b.txt", "tampered");

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(2, results.size());
        HashUtil.CheckResult a = results.get(0);
        HashUtil.CheckResult b = results.get(1);
        assertTrue(a.valid);
        assertFalse("changed file must fail", b.valid);
        assertNotNull("changed file has actual hash", b.actual);
        assertFalse(b.missing);
        assertFalse(b.rejected);
        assertEquals(hashOfFile("tampered", "MD5"), b.actual);
    }

    @Test
    public void verifyReportsMissingEntry() throws Exception {
        write(dir, "a.txt", "hello");
        File manifest = write(dir, "payload.md5",
                hashOfFile("hello", "MD5") + "  a.txt\n"
                        + hashOfFile("ghost", "MD5") + "  ghost.txt\n");

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(2, results.size());
        assertTrue(results.get(0).valid);
        HashUtil.CheckResult ghost = results.get(1);
        assertFalse(ghost.valid);
        assertTrue("absent target flagged missing", ghost.missing);
        assertNull(ghost.actual);
    }

    @Test
    public void unsafeEntryNamesAreRejectedAndNeverOpened() throws Exception {
        File outside = write(folder.getRoot(), "outside.txt", "secret");
        write(dir, "a.txt", "hello");
        String h = hashOfFile("secret", "MD5");
        File manifest = write(dir, "payload.md5",
                h + "  ../outside.txt\n"
                        + h + "  /etc/outside.txt\n"
                        + h + "  C:\\outside.txt\n"
                        + h + "  a/../../outside.txt\n"
                        + h + "  sub\\..\\..\\outside.txt\n");

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(5, results.size());
        for (HashUtil.CheckResult r : results) {
            assertTrue(r.fileName + " rejected", r.rejected);
            assertFalse(r.valid);
            assertNull("never opened, so no actual hash", r.actual);
        }
        // The traversal target itself was never read or modified.
        assertEquals("secret", new String(java.nio.file.Files.readAllBytes(outside.toPath()),
                StandardCharsets.UTF_8));
    }

    @Test
    public void sanitizeEntryNameRules() {
        assertEquals("a.txt", HashUtil.sanitizeEntryName("./a.txt"));
        assertEquals("sub/a.txt", HashUtil.sanitizeEntryName("sub/a.txt"));
        assertEquals("sub/a.txt", HashUtil.sanitizeEntryName("sub\\a.txt"));
        assertNull("empty", HashUtil.sanitizeEntryName(""));
        assertNull("absolute", HashUtil.sanitizeEntryName("/etc/passwd"));
        assertNull("parent traversal", HashUtil.sanitizeEntryName("../x"));
        assertNull("inner traversal", HashUtil.sanitizeEntryName("a/../b"));
        assertNull("dot segment", HashUtil.sanitizeEntryName("a/./b"));
        assertNull("empty segment", HashUtil.sanitizeEntryName("a//b"));
        assertNull("windows drive", HashUtil.sanitizeEntryName("C:\\x"));
        assertNull("windows drive forward", HashUtil.sanitizeEntryName("C:/x"));
        assertNull("alternate data stream", HashUtil.sanitizeEntryName("x:y"));
        assertNull("null byte", HashUtil.sanitizeEntryName("a\0b"));
    }

    @Test
    public void bsdStyleMd5LineParsesAndVerifies() throws Exception {
        write(dir, "a.txt", "abc");
        File manifest = write(dir, "payload.md5", "MD5 (a.txt) = 900150983cd24fb0d6963f7d28e17f72\n");

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(1, results.size());
        assertTrue(results.get(0).valid);
        assertEquals("a.txt", results.get(0).fileName);
    }

    @Test
    public void binaryMarkerStrippedFromMd5sumLine() {
        HashUtil.ManifestEntry e = HashUtil.parseManifestLine("MD5",
                "5d41402abc4b2a76b9719d911017c592 *a.txt", 1);
        assertNotNull(e);
        assertFalse(e.rejected);
        assertEquals("a.txt", e.name);
    }

    @Test
    public void commentsBlankAndGarbageLinesSkipped() throws Exception {
        File manifest = write(dir, "payload.md5",
                "; comment\n# comment\n\nnot-a-hash-line\ntoo short\n");
        List<HashUtil.ManifestEntry> entries;
        try (java.io.BufferedReader br = new java.io.BufferedReader(
                new java.io.InputStreamReader(new FileInputStream(manifest), StandardCharsets.UTF_8))) {
            entries = HashUtil.parseManifest("MD5", br);
        }
        assertEquals(0, entries.size());
    }

    @Test
    public void sfvLineRequiresEightHexCrc() {
        assertNull(HashUtil.parseManifestLine("CRC32", "a.txt ZZZ", 1));
        assertNull(HashUtil.parseManifestLine("CRC32", "a.txt 1234567", 1));
        assertNull(HashUtil.parseManifestLine("CRC32", "a.txt", 1));
        HashUtil.ManifestEntry ok = HashUtil.parseManifestLine("CRC32", "a.txt 12345678", 3);
        assertNotNull(ok);
        assertEquals("a.txt", ok.name);
        assertEquals("12345678", ok.expected);
        assertEquals(3, ok.line);
    }

    @Test
    public void sfvLineAcceptsTabSeparator() {
        HashUtil.ManifestEntry e = HashUtil.parseManifestLine("CRC32", "a.txt\tCBF43926", 1);
        assertNotNull(e);
        assertFalse(e.rejected);
        assertEquals("a.txt", e.name);
        assertEquals("cbf43926", e.expected);
    }

    @Test
    public void manifestReaderDecodesUtf8AndFallsBackToLatin1() throws Exception {
        String expected = new String(new byte[]{'c', 'a', 'f', (byte) 0xE9, '.', 't', 'x', 't'},
                StandardCharsets.ISO_8859_1);
        assertEquals(expected,
                HashUtil.openManifestReader(new ByteArrayInputStream(
                        expected.getBytes(StandardCharsets.UTF_8))).readLine());
        // Invalid UTF-8 (lone 0xE9) must fall back to ISO-8859-1, not turn
        // into U+FFFD garbage.
        assertEquals(expected,
                HashUtil.openManifestReader(new ByteArrayInputStream(
                        new byte[]{'c', 'a', 'f', (byte) 0xE9, '.', 't', 'x', 't'})).readLine());
    }

    @Test
    public void verifyResolvesSanitizedSubdirectoryEntries() throws Exception {
        new File(dir, "sub").mkdirs();
        write(dir, "sub" + File.separator + "a.txt", "hello");
        File manifest = write(dir, "payload.sfv",
                "sub/a.txt " + hashOfFile("hello", "CRC32").toUpperCase() + "\r\n");

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(manifest);

        assertEquals(1, results.size());
        assertTrue(results.get(0).valid);
        assertEquals("sub/a.txt", results.get(0).fileName);
    }

    @Test
    public void manifestReaderClosesItsSourceAndAcceptsUtf8Bom() throws Exception {
        boolean[] closed = {false};
        ByteArrayInputStream source = new ByteArrayInputStream(
                ("\uFEFF900150983cd24fb0d6963f7d28e17f72  a.txt\n").getBytes(StandardCharsets.UTF_8)) {
            @Override public void close() throws java.io.IOException {
                closed[0] = true;
                super.close();
            }
        };
        List<HashUtil.ManifestEntry> entries;
        try (java.io.BufferedReader reader = HashUtil.openManifestReader(source)) {
            entries = HashUtil.parseManifest("MD5", reader);
        }
        assertTrue("Manifest input streams must be closed", closed[0]);
        assertEquals(1, entries.size());
        assertEquals("a.txt", entries.get(0).name);
    }

    @Test
    public void generationRejectsNamesThatCannotRoundTrip() {
        assertTrue(HashUtil.canGenerateEntry("two spaces  café.txt", true));
        assertTrue(HashUtil.canGenerateEntry("#name.txt", false));
        for (String name : List.of(" leading", "trailing ", "line\nbreak", "line\rbreak",
                "a\\b", "a/b", "a:b")) {
            assertFalse(name, HashUtil.canGenerateEntry(name, true));
            assertFalse(name, HashUtil.canGenerateEntry(name, false));
        }
        assertFalse(HashUtil.canGenerateEntry(";comment", true));
        assertFalse(HashUtil.canGenerateEntry("#comment", true));
        assertFalse(HashUtil.canGenerateEntry("*binary-marker", false));
    }

    @Test
    public void algorithmForChecksumFileBasics() {
        assertEquals("CRC32", HashUtil.algorithmForChecksumFile("X.SFV"));
        assertEquals("MD5", HashUtil.algorithmForChecksumFile("x.md5"));
        assertEquals("SHA-256", HashUtil.algorithmForChecksumFile("x.sha256"));
        assertNull(HashUtil.algorithmForChecksumFile("x.txt"));
    }

    @Test
    public void openerDrivenVerificationResolvesOutsideTheManifestFolder() throws Exception {
        // Simulates the staged-manifest case: manifest bytes in one folder,
        // targets resolved elsewhere through the opener.
        File staged = write(folder.newFolder("stage"), "payload.md5",
                hashOfFile("hello", "MD5") + "  a.txt\n");
        write(dir, "a.txt", "hello");

        List<HashUtil.CheckResult> results = HashUtil.verifyChecksumFile(staged,
                rel -> new FileInputStream(new File(dir, rel)));

        assertEquals(1, results.size());
        assertTrue(results.get(0).valid);
    }

    @Test
    public void verifyEntriesMarksRejectedWithoutCallingOpener() {
        HashUtil.ManifestEntry good = HashUtil.parseManifestLine("MD5",
                "5d41402abc4b2a76b9719d911017c592 a.txt", 1);
        HashUtil.ManifestEntry bad = HashUtil.parseManifestLine("MD5",
                "5d41402abc4b2a76b9719d911017c592 ../a.txt", 2);
        assertNotNull(good);
        assertNotNull(bad);
        assertTrue(bad.rejected);

        boolean[] opened = {false};
        List<HashUtil.CheckResult> results = verify(new HashUtil.ManifestEntry[]{bad, good}, "MD5", rel -> {
            opened[0] = true;
            return new ByteArrayInputStream("hello".getBytes(StandardCharsets.UTF_8));
        });

        assertEquals(2, results.size());
        assertTrue(results.get(0).rejected);
        assertFalse(results.get(0).valid);
        assertTrue("opener ran for the safe entry only", opened[0]);
        assertTrue(results.get(1).valid);
    }
}
